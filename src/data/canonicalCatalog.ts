export const CANONICAL_TOOLS_MAP: Record<string, CanonicalToolDefinition> = Object.fromEntries(
  CANONICAL_TOOLS.map((t) => [t.tool_id, t])
);

export function getCanonicalTool(toolId: string): CanonicalToolDefinition | undefined {
  return CANONICAL_TOOLS.find((t) => t.tool_id === toolId);
}

export function isToolReversible(toolId: string): boolean {
  const tool = getCanonicalTool(toolId);
  return tool ? tool.is_reversible : false;
}

export function getToolRiskLevel(toolId: string): ToolRiskLevel {
  const tool = getCanonicalTool(toolId);
  return tool ? tool.risk_level : 'SAFE';
}

export function getToolRequiredPlan(toolId: string): PlanLevel {
  const tool = getCanonicalTool(toolId);
  return tool ? tool.required_plan_level : 1;
}
